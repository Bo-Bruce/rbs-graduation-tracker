// Rebuild the "course number -> SAS Core code" table embedded in index.html.
// Source: Rutgers Schedule of Classes public JSON (no login), New Brunswick, several recent terms.
// Usage: node tools/build-core-codes.mjs [firstYear] [lastYear]     e.g. node tools/build-core-codes.mjs 2024 2027
import {readFileSync, writeFileSync} from 'node:fs';

const KEEP = new Set(['AHo', 'AHp', 'AHq', 'AHr', 'CCD', 'CCO', 'HST', 'NS', 'QQ', 'QR', 'SCL', 'WC', 'WCd', 'WCr']);
const TERMS = [['0', 'Winter'], ['1', 'Spring'], ['7', 'Summer'], ['9', 'Fall']];
const now = new Date().getFullYear();
const [y0, y1] = [+(process.argv[2] || now - 2), +(process.argv[3] || now + 1)];

const map = new Map(), used = [];
for (let y = y0; y <= y1; y++) for (const [t, name] of TERMS){
  const url = `https://classes.rutgers.edu/soc/api/courses.json?year=${y}&term=${t}&campus=NB`;
  let data;
  try {
    const r = await fetch(url, {headers: {'User-Agent': 'rbs-graduation-tracker (static course planner)'}});
    if (!r.ok) throw new Error('HTTP ' + r.status);
    data = await r.json();
  } catch (e){ console.log(`skip ${name} ${y}: ${e.message}`); continue; }
  if (!Array.isArray(data) || !data.length){ console.log(`skip ${name} ${y}: empty`); continue; }
  let n = 0;
  for (const c of data){
    const codes = (c.coreCodes || []).map(x => x.coreCode || x.code).filter(x => KEEP.has(x));
    if (!codes.length || !/^\d{2}:\d{3}:\d{3}$/.test(c.courseString || '')) continue;
    const s = map.get(c.courseString) || new Set(); codes.forEach(x => s.add(x)); map.set(c.courseString, s); n++;
  }
  used.push(`${name} ${y}`); console.log(`${name} ${y}: ${data.length} courses, ${n} with SAS Core codes`);
  await new Promise(r => setTimeout(r, 400));   // be gentle with the public endpoint
}
if (!map.size) throw new Error('no data fetched');

// Compact form: "0101312 0:HST|..." -> code without colons : codes joined by spaces
const body = [...map.keys()].sort().map(k => k.replace(/:/g, '') + ':' + [...map.get(k)].sort().join(' ')).join('|');
const today = new Date().toISOString().slice(0, 10);
const block = `/* CORE-DATA:BEGIN (generated by tools/build-core-codes.mjs — do not edit by hand) */
const CORE_DATA = {updated:'${today}', terms:'${used[0]} – ${used[used.length - 1]}', count:${map.size},
  table:'${body}'};
/* CORE-DATA:END */`;
const html = readFileSync('index.html', 'utf8');
const re = /\/\* CORE-DATA:BEGIN[\s\S]*?\/\* CORE-DATA:END \*\//;
if (!re.test(html)) throw new Error('CORE-DATA markers not found in index.html');
writeFileSync('index.html', html.replace(re, block));
console.log(`wrote ${map.size} courses (${(body.length / 1024).toFixed(1)} KB) from ${used.length} terms`);
